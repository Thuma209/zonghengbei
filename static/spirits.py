def reload_from_db(db_manager) -> None:
    """从 DB 加载精神定义到 SPIRIT_SPECS。引擎运行每个回合前调用一次。"""
    loaded = db_manager.load_spirit_definitions()
    SPIRIT_SPECS.clear()
    SPIRIT_SPECS.update(loaded if loaded else _DEFAULT_SPECS)


